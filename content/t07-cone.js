function J2sqrti(q) {
  const zr = q / Math.SQRT2, zi = q / Math.SQRT2;               // z = q(1+i)/√2
  const hr = zr / 2, hi = zi / 2;                               // z/2
  const h2r = hr * hr - hi * hi, h2i = 2 * hr * hi;             // (z/2)^2
  let tr = h2r / 2, ti = h2i / 2;                               // k = 0 term: (z/2)^2 / (0! 2!)
  let sr = tr, si = ti;
  for (let k = 1; k < 80; k++) {
    // term_k = term_{k-1} * (-(z/2)^2) / (k (k+2))
    const f = -1 / (k * (k + 2));
    const nr = (tr * h2r - ti * h2i) * f, ni = (tr * h2i + ti * h2r) * f;
    tr = nr; ti = ni; sr += tr; si += ti;
    if (Math.abs(tr) + Math.abs(ti) < 1e-17 * (Math.abs(sr) + Math.abs(si))) break;
  }
  return [sr, si];
}

