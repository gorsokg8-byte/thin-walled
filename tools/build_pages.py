"""Prepare the app for GitHub Pages: home-screen icons and the offline service worker (sw.js).

Run before every commit that changes the app:  python tools/build_pages.py
sw.js gets the list of all app files and a version hash, so phones pick up the update.
"""
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SKIP_DIRS = {'_work', 'dist', 'tools', '.git', '.claude', '__pycache__'}
SKIP_FILES = {'sw.js', 'README.md', '.gitignore'}


def make_icons():
    out = ROOT / 'icons'
    out.mkdir(exist_ok=True)
    s = 512
    img = Image.new('RGB', (s, s), (31, 95, 139))
    d = ImageDraw.Draw(img)
    # dome (shell of revolution) on a plate
    d.pieslice([96, 120, 416, 440], 180, 360, outline=(255, 255, 255), width=26)
    d.line([56, 280, 456, 280], fill=(255, 255, 255), width=26)
    d.line([256, 80, 256, 300], fill=(160, 200, 230), width=6)
    for size, name in [(512, 'icon-512.png'), (192, 'icon-192.png'), (180, 'apple-touch-icon.png')]:
        img.resize((size, size), Image.LANCZOS).save(out / name)


def app_files():
    files = []
    for p in sorted(ROOT.rglob('*')):
        rel = p.relative_to(ROOT)
        if p.is_dir() or rel.parts[0] in SKIP_DIRS or rel.name in SKIP_FILES:
            continue
        if p.suffix in {'.ttf', '.woff'}:   # browsers use woff2
            continue
        files.append(rel.as_posix())
    return files


def make_sw(files):
    h = hashlib.sha256()
    for f in files:
        h.update((ROOT / f).read_bytes())
    version = h.hexdigest()[:12]
    lst = ',\n  '.join(f"'./{f}'" for f in files)
    sw = f"""// Generated by tools/build_pages.py — do not edit by hand.
// Network first (fresh content when online), cache as fallback (works offline).
const CACHE = 'thin-walled-{version}';
const FILES = [
  './',
  {lst}
];
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET') return;
  e.respondWith(fetch(e.request).then(r => {{
    const copy = r.clone();
    caches.open(CACHE).then(c => c.put(e.request, copy));
    return r;
  }}).catch(() => caches.match(e.request, {{ ignoreSearch: true }})));
}});
"""
    (ROOT / 'sw.js').write_text(sw, encoding='utf-8')
    return version


if __name__ == '__main__':
    make_icons()
    files = app_files()
    v = make_sw(files)
    print(len(files), 'files cached, version', v)
